package com.oops.mol;

public class TestMOLDemo1 {

	public static void main(String[] args) {

		TestMOLDemo1 t = new TestMOLDemo1();

		byte b = 10;
		System.out.println(b);

		System.out.println(100);// int
		System.out.println(9972677655L);// long
		System.out.println(5.9F);// float
		System.out.println(65.0);// double

		System.out.println('A');// char
		System.out.println(true);// boolean

		System.out.println("Good evening !");// String
		System.out.println(t);// Object
		System.out.println();// empty args

		int[] n = { 1, 2, 3 };
		System.out.println(n);// Address of the object

		char[] ch = { 'A', 'P', 'P' };
		System.out.println(ch);// APP

	}

}
